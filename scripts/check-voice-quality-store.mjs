import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const source=stripTypeScriptTypes(readFileSync(new URL('../src/lib/voiceQualityStore.ts',import.meta.url),'utf8'),{mode:'transform'});
const {VoiceQualityStore}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const report=(gen=1,seq=1)=>({schemaVersion:1,connectionGeneration:gen,seq,iceRttMs:40,uplink:{rttMs:60,sample:{windowMs:2000,packetsReceived:100,packetsLost:2}},receive:{jitterMaxMs:7,sample:null}});
const update=(r=report(),id='a')=>({schemaVersion:1,clientId:id,report:r,receivedAt:100000,expiresAt:108000});
const known=new Set(['a']); const store=new VoiceQualityStore();
assert.equal(store.accept(update(),known,1000),true);assert.equal(store.read('a',1000).iceRttMs,40);
assert.equal(store.accept(update(report(1,1)),known,1001),false);
assert.equal(store.accept(update(report(1,2),'stranger'),known,1002),false);
assert.equal(store.accept({...update(report(1,2)),address:'private'},known,1002),false);
assert.equal(store.accept(update({...report(1,2),iceRttMs:Infinity}),known,1003),false);
assert.equal(store.accept(update({...report(1,2),uplink:{rttMs:1,sample:{windowMs:2000,packetsReceived:0,packetsLost:-1}}}),known,1003),false);
assert.equal(store.read('a',9000),undefined);assert.equal(store.accept(update(report(1,1)),known,9001),false,'expiry does not reset watermark');
assert.equal(store.accept(update(report(2,1)),known,9002),true);assert.equal(store.accept(update(report(1,999)),known,9003),false);
assert.equal(store.accept(update(null),known,9004),true);assert.equal(store.read('a',9004),undefined);
assert.equal(store.accept(update(report(2,1)),known,9005),false,'clear preserves watermark');
assert.equal(store.accept(update(report(2,2)),known,9006),true);
store.retain(new Set());assert.equal(store.read('a',9007),undefined);
assert.equal(store.accept(update(report(2,2)),known,9008),false,'roster removal preserves watermark within socket generation');
store.reset();assert.equal(store.accept(update(report()),known,9009),true);
const bad=update(report(1,2));bad.expiresAt=bad.receivedAt+9000;assert.equal(store.accept(bad,known,9010),false);
const mutable=update(report(1,2));assert.equal(store.accept(mutable,known,9011),true);mutable.report.iceRttMs=999;assert.equal(store.read('a',9011).iceRttMs,40);
console.log('18 quality summary identity/expiry/order/validation checks passed');
