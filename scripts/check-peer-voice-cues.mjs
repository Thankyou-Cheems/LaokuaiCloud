import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const source=stripTypeScriptTypes(readFileSync(new URL('../src/lib/peerVoiceCues.ts',import.meta.url),'utf8'),{mode:'transform'});
const {PeerCuePolicy,resolvePeerCueSettings,peerCuePcm}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const policy=new PeerCuePolicy();
const base={connectionKey:'host/room/g1',selfId:'self',memberId:'peer',kind:'join',eligible:true,now:1000};
assert.equal(policy.accept({...base,eligible:false}),false);
assert.equal(policy.accept({...base,memberId:'self'}),false);
assert.equal(policy.accept(base),true);assert.equal(policy.accept(base),false);
assert.equal(policy.accept({...base,memberId:'b',now:1200}),false);
assert.equal(policy.accept({...base,kind:'leave',now:1500}),true);
assert.equal(policy.accept({...base,connectionKey:'host/room/g2',now:1501}),true);
assert.equal(policy.accept({...base,connectionKey:'host/room/g2',now:1502}),false);
const invalid=resolvePeerCueSettings({enabled:'true',dnd:1,joinVolume:Infinity,leaveVolume:-20});
assert.equal(invalid.enabled,true);assert.equal(invalid.dnd,false);assert.equal(invalid.joinVolume,60);assert.equal(invalid.leaveVolume,0);
const join=peerCuePcm('join',48000),leave=peerCuePcm('leave',48000);
assert.equal(join.length,8640);assert.equal(join[0],0);assert.equal(join.at(-1),0);
assert.ok(join.every(Number.isFinite));assert.ok(Math.max(...join)<=0.18001);
assert.notDeepEqual(join,leave);
assert.throws(()=>peerCuePcm('join',0));
console.log('11 peer-cue policy/config/PCM checks passed');
