import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
const moduleUrl=code=>'data:text/javascript;base64,'+Buffer.from(code).toString('base64');
const contract=moduleUrl(stripTypeScriptTypes(readFileSync(new URL('../src/lib/nativeLanAudio.ts',import.meta.url),'utf8'),{mode:'transform'}));
const sessionSource=stripTypeScriptTypes(readFileSync(new URL('../src/lib/nativeRoomSession.ts',import.meta.url),'utf8'),{mode:'transform'}).replace('"./nativeLanAudio"',JSON.stringify(contract));
const {createNativeRoomSession}=await import(moduleUrl(sessionSource));
let now=1000;
const room=createNativeRoomSession('server','room',()=>now);
const controls={muted:false,deafened:false,pttRequired:false,pttHeld:false,suppressed:false,inputGain:1,outputGain:1,memberVolumes:{peer:0.5}};
const snapshot={v:1,serverId:'server',channelId:'room',revision:1,epoch:'epoch',localIp:'10.203.217.1',key:'a'.repeat(64),peers:[{userId:'peer',virtualIp:'10.203.217.2',canPublish:true,canReceive:true}],serverTimeMs:4000,expiresAtMs:19000,canPublish:true,canReceive:true,requirePTT:false};
assert.equal(room.desired(controls),null);
assert.equal(room.accept(snapshot),true);
assert.equal(room.desired(controls).muted,false);
assert.equal(room.desired(controls).memberVolumes.peer,0.5);
assert.equal(room.accept(snapshot),false);
assert.equal(room.accept({...snapshot,serverId:'other',revision:2}),false);
assert.equal(room.accept({...snapshot,localIp:'127.0.0.1',revision:2}),false);
assert.equal(room.accept({...snapshot,key:'0'.repeat(64),revision:2}),false);
assert.equal(room.accept({...snapshot,expiresAtMs:20000,revision:2}),false);
assert.equal(room.desired({...controls,muted:true}).muted,true);
assert.equal(room.desired({...controls,deafened:true}).deafened,true);
assert.equal(room.desired({...controls,suppressed:true}).muted,true);
assert.equal(room.desired({...controls,pttRequired:true}).muted,true);
assert.equal(room.desired({...controls,pttRequired:true,pttHeld:true}).muted,false);
now=5000;
assert.equal(room.accept({...snapshot,serverTimeMs:8000,expiresAtMs:23000}),true);
assert.equal(room.accept({...snapshot,serverTimeMs:7000,expiresAtMs:22000}),false);
assert.equal(room.accept({...snapshot,revision:2,canPublish:false,requirePTT:true}),true);
assert.equal(room.desired({...controls,pttHeld:true}).muted,true);
assert.equal(room.accept({...snapshot,channelId:'destination',revision:3}),false);
room.move('destination');
assert.equal(room.accept({...snapshot,channelId:'room',revision:3}),false);
assert.equal(room.accept({...snapshot,channelId:'destination',revision:1}),true);
assert.equal(room.room,'destination');
room.suspend();assert.equal(room.desired(controls),null);
assert.equal(room.accept({...snapshot,channelId:'destination',revision:4}),true);
now+=15000;assert.equal(room.desired(controls),null);
room.close();assert.equal(room.active,false);
assert.equal(room.accept({...snapshot,channelId:'destination',revision:5}),false);
assert.equal(room.desired(controls),null);
const solo=createNativeRoomSession('server','room',()=>now);
assert.equal(solo.accept({...snapshot,peers:[]}),true);
assert.equal(solo.desired(controls).peers.length,0);
console.log('27 native room lease, identity, mute/PTT/Squad, private snapshot, move and solo checks passed; no devices or sockets.');
