import ts from 'typescript';
import { readFileSync, writeFileSync } from 'node:fs';
const source = ['receiveLevelingCore.ts', 'receiveLongTermCore.ts'].map(name =>
  readFileSync('src/audio/processors/' + name, 'utf8').split('// Original receiver gain/compressor;')[0]).join('\n');
// Type-only imports must not make TypeScript emit a CommonJS module wrapper in the worklet.
const plainSource = source.replace(/^import type [^;]+;\s*/gm, '').replaceAll('export ', '');
if (/^import\s/m.test(plainSource)) throw new Error('Runtime imports are not supported in inline receive DSP');
const code = ts.transpileModule(plainSource, {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.None },
}).outputText;
if (/Object\.defineProperty\(exports|\brequire\(/.test(code))
  throw new Error('Inline DSP contains a module wrapper');
const output = '// Generated by scripts/generate-receive-dsp.mjs; preserve the MIT attribution in the code.\n' +
  'export const RECEIVE_DSP_CODE = ' + JSON.stringify(code) + ';\n';
const path = 'src/audio/processors/receiveDspCode.ts';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error('Receive DSP code is stale');
} else writeFileSync(path, output);
