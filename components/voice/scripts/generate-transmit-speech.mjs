import { readFileSync, writeFileSync } from 'node:fs';
import ts from 'typescript';
const runtime = readFileSync('src/audio/processors/receiveLongTermCore.ts', 'utf8');
const start = runtime.indexOf('export function createReceiveAnalyzerRuntime');
const end = runtime.indexOf('export class ReceiveLongTermLeveler', start);
const source = runtime.slice(start, end) + readFileSync('src/audio/processors/adaptiveTransmitGate.ts', 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020,
  module: ts.ModuleKind.ESNext } }).outputText.replace(/^export /gm, '').replace(/^import .*;\r?\n/gm, '');
const output = '// Generated by scripts/generate-transmit-speech.mjs.\nexport const TRANSMIT_SPEECH_CORE_CODE = ' + JSON.stringify(code) + ';\n';
const path = 'src/audio/processors/transmitSpeechCode.ts';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('transmit speech worklet core is stale');
} else writeFileSync(path, output);
