const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),{spawnSync}=require('node:child_process');
const root=path.resolve(__dirname,'../../..');
const manifest=JSON.parse(fs.readFileSync(path.join(__dirname,'manifest.json'),'utf8'));
const git=args=>{const result=spawnSync('git',args,{cwd:root,windowsHide:true,encoding:'utf8'});assert.equal(result.status,0,result.stderr);return result.stdout.trim();};
const sha=file=>crypto.createHash('sha256').update(fs.readFileSync(path.join(root,file))).digest('hex');
const client=manifest.repositories.client,voice=manifest.repositories.voice;
assert.equal(manifest.schema,1);
assert.match(client.commit,/^[0-9a-f]{40}$/);
assert.equal(git(['rev-parse',`${client.commit}^{tree}`]),client.tree);
git(['merge-base','--is-ancestor',client.completeSnapshot,client.commit]);
git(['merge-base','--is-ancestor',client.commit,'HEAD']);
const inputs=['src','electron','native','private-brand','public','scripts','package.json','yarn.lock','index.html','vite.config.ts','electron-builder.yml','electron-builder.config.cjs','electron-builder.i18n-test.cjs','electron-builder.laokuai.cjs'];
assert.equal(git(['diff','--name-only',client.commit,'HEAD','--',...inputs]),'','Build inputs changed after frozen source commit');
assert.equal(git(['diff','--name-only','HEAD','--',...inputs]),'','Dirty build inputs are not frozen');
assert.equal(git(['diff','--cached','--name-only','--',...inputs]),'','Staged build inputs are not frozen');
assert.equal(git(['ls-files','--others','--exclude-standard','--',...inputs]),'','Untracked build inputs are not frozen');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
assert.equal(pkg.version,client.version);
assert.equal(pkg.devDependencies['@gryt/voice'],`file:${voice.activePackage.path}`);
assert.equal(sha(voice.activePackage.path),voice.activePackage.sha256);
assert.equal(sha(manifest.cleanupReview.reviewedPatch),manifest.cleanupReview.reviewedPatchSha256);
assert.ok(manifest.integratedDeliveries.every(d=>d.conflicts.length===0));
assert.equal(manifest.validation.clientPure.status,'passed');
assert.equal(manifest.validation.clientPure.commit,client.commit);
assert.ok(manifest.validation.clientPure.checks.every(c=>c.exit===0));
assert.equal(manifest.finalArtifact.built,false);
assert.equal(manifest.ready,false);
console.log(`PASS frozen source ${client.commit}, package SHA256, review patch, delivery sequence and pending gates.`);
if(process.argv.includes('--require-ready')) {console.error(`NOT READY: ${manifest.pending.join('; ')}`);process.exitCode=2;}
